#!/usr/bin/env python3
"""
Song compiler and build pipeline for sid_player.asm (the 3-voice tracker driver
in this folder).

A song is a Python file that defines:
  TITLE            short name used in generated comments
  INSTRUMENTS      {name: dict(ad, sr, pw, pws, vib, wave=[(waveform, pitch)...], loop)}
                   pitch: semitones above the played note, or ("abs", note)
                   loop: wavetable step to return to after the last (None = hold last)
  PATTERNS         {name: [(instrument, note name or None, rows), ...]}
  ORDERS           three (sequence, loop index) pairs, one per voice; a sequence
                   holds pattern names and ("T", semitones) transpose markers
  FILTER_CUTOFF    $D416 value
  FILTER_ROUTING   $D417 value (resonance << 4 | voice bits)
optional:
  SUMMARY          dict for review pages (bars, chords, voices...); written to music.json
  ASM              music block source next to the song (default "music.asm"), which
                   #imports music_config.asm, sid_player.asm and music_data.asm
  SID              dict(name, author, released, file) for the .sid export
  SIM_FRAMES       frames to emulate for the register log (default 1800)

Steps: song -> music_data.asm + music_config.asm (+ music.json)
       --build: KickAssembler -> music.prg -> 6502 emulation (sid_log.json,
       CPU time per frame) -> .sid file

  python song_tool.py ../../game_dev/ironfront/music/ironfront_march.py --build
"""
import argparse
import importlib.util
import json
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
TOOLS = HERE.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(TOOLS / "sim6502"))

NOTE = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}


# ---------------------------------------------------------------- helpers for song files
def n(name):
    """'C#5', 'Bb4', 'A2' -> note number with C0 = 0."""
    base = NOTE[name[0]]
    rest = name[1:]
    while rest and rest[0] in "#b":
        base += 1 if rest[0] == "#" else -1
        rest = rest[1:]
    return int(rest) * 12 + base


def bar(inst, *pairs, rows=16):
    """One bar of (note name or '-', rows) pairs for one instrument."""
    ev = [(inst, None if p == "-" else p, d) for p, d in pairs]
    assert sum(d for _, _, d in ev) == rows, (inst, pairs)
    return ev


def drum_bar(spec, kit, rows=16):
    """'K2 s1 R4' with kit {'K': 'kick', ...} -> events (drums play fixed pitches)."""
    ev = [(kit[tok[0]], "C4", int(tok[1:])) for tok in spec.split()]
    assert sum(d for _, _, d in ev) == rows, spec
    return ev


# ---------------------------------------------------------------- encoding
def encode_pattern(events, inst_order):
    out, inst, dur = [], None, None
    for ins, note, rows in events:
        if ins != inst:
            out.append(0xC0 + inst_order.index(ins))
            inst = ins
        if rows != dur:
            assert 1 <= rows <= 64, rows
            out.append(0x80 + rows - 1)
            dur = rows
        out.append(0 if note is None else n(note))
    return out + [0xFF]


def encode_order(seq, loop, pat_index):
    out, pos_of = [], []
    for item in seq:
        pos_of.append(len(out))
        out.append(0xA0 + item[1] if isinstance(item, tuple) else pat_index[item])
    return out + [0xFF, pos_of[loop]]


def build_wavetable(instruments):
    waves, arps, start = [], [], {}
    for name, ins in instruments.items():
        start[name] = len(waves)
        for wave, pitch in ins["wave"]:
            waves.append(wave)
            arps.append(0x80 | pitch[1] if isinstance(pitch, tuple) else pitch)
        target = start[name] + (len(ins["wave"]) - 1 if ins["loop"] is None else ins["loop"])
        waves.append(0xFF)
        arps.append(target)
    return waves, arps, start


def bytes_line(label, values):
    lines = [f"{label}:"]
    for i in range(0, len(values), 16):
        lines.append("    .byte " + ",".join(f"${v & 0xFF:02X}" for v in values[i:i + 16]))
    return lines


def load_song(path):
    spec = importlib.util.spec_from_file_location(path.stem, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def compile_song(song, outdir):
    inst_order = list(song.INSTRUMENTS)
    names = list(song.PATTERNS)
    pat_index = {k: i for i, k in enumerate(names)}
    waves, arps, wstart = build_wavetable(song.INSTRUMENTS)
    out = [
        f"// {song.TITLE} - generated by tools/sid/song_tool.py, do not edit by hand",
        "ol_lo: .byte <ol_v1, <ol_v2, <ol_v3",
        "ol_hi: .byte >ol_v1, >ol_v2, >ol_v3",
    ]
    for v, (seq, loop) in enumerate(song.ORDERS, 1):
        out += bytes_line(f"ol_v{v}", encode_order(seq, loop, pat_index))
    out.append("pat_lo: .byte " + ",".join(f"<pat_{k}" for k in names))
    out.append("pat_hi: .byte " + ",".join(f">pat_{k}" for k in names))
    for k in names:
        out += bytes_line(f"pat_{k}", encode_pattern(song.PATTERNS[k], inst_order))
    ins = [song.INSTRUMENTS[k] for k in inst_order]
    out.append("// instruments: " + ", ".join(f"{i}={k}" for i, k in enumerate(inst_order)))
    for label, key in (("ins_ad", "ad"), ("ins_sr", "sr"), ("ins_pws", "pws"), ("ins_vib", "vib")):
        out += bytes_line(label, [i[key] for i in ins])
    out += bytes_line("ins_pwlo", [i["pw"] & 0xFF for i in ins])
    out += bytes_line("ins_pwhi", [i["pw"] >> 8 for i in ins])
    out += bytes_line("ins_wave", [wstart[k] for k in inst_order])
    out += bytes_line("wt_wave", waves)
    out += bytes_line("wt_arp", arps)
    (outdir / "music_data.asm").write_text("\n".join(out) + "\n", encoding="utf-8")
    # constants go in their own file: KickAssembler needs them before the driver uses them
    (outdir / "music_config.asm").write_text(
        f"// {song.TITLE} settings - generated by tools/sid/song_tool.py\n"
        f".const FILTER_CUTOFF = ${song.FILTER_CUTOFF:02X}\n"
        f".const FILTER_ROUTING = ${song.FILTER_ROUTING:02X}\n", encoding="utf-8")
    summary = dict(getattr(song, "SUMMARY", {}))
    summary["instruments"] = [{"name": k, "ad": f"${v['ad']:02X}", "sr": f"${v['sr']:02X}", "steps": len(v["wave"])}
                              for k, v in song.INSTRUMENTS.items()]
    (outdir / "music.json").write_text(json.dumps(summary, indent=1), encoding="utf-8")
    print(f"compiled {song.TITLE}: {len(names)} patterns, {len(waves)} wavetable steps")


def build(song, outdir, kickass):
    import make_psid
    import sim6502

    asm = outdir / getattr(song, "ASM", "music.asm")
    res = subprocess.run(["java", "-jar", str(kickass), asm.name], cwd=outdir, capture_output=True, text=True)
    if res.returncode != 0 or "Error" in res.stdout:
        raise SystemExit("KickAssembler failed:\n" + res.stdout + res.stderr)
    (outdir / asm.with_suffix(".sym").name).unlink(missing_ok=True)
    prg = (outdir / asm.with_suffix(".prg").name).read_bytes()
    print(f"assembled {asm.with_suffix('.prg').name}: {len(prg) - 2} bytes at ${prg[0] | prg[1] << 8:04X}")

    frames = getattr(song, "SIM_FRAMES", 1800)
    regs, cyc = sim6502.run(prg, 0x1000, 0x1003, frames)
    (outdir / "sid_log.json").write_text(json.dumps({
        "frames": len(regs), "maxCycles": max(cyc),
        "regs": ["".join(f"{v:02x}" for v in r) for r in regs]}))
    print(f"emulated {frames} frames: play routine {min(cyc)}-{max(cyc)} cycles "
          f"(max {max(cyc) / 63:.1f} PAL raster lines)")

    meta = getattr(song, "SID", {})
    sid_path = outdir / meta.get("file", asm.with_suffix(".sid").name)
    sid_path.write_bytes(make_psid.make_psid(prg, 0x1000, 0x1003, meta.get("name", song.TITLE),
                                             meta.get("author", ""), meta.get("released", "")))
    print(f"wrote {sid_path.name}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("song", type=pathlib.Path)
    ap.add_argument("--build", action="store_true", help="also assemble, emulate and export .sid")
    ap.add_argument("--kickass", type=pathlib.Path, default=TOOLS / "kickassembler" / "KickAss.jar")
    args = ap.parse_args()
    song_path = args.song.resolve()
    song = load_song(song_path)
    compile_song(song, song_path.parent)
    if args.build:
        build(song, song_path.parent, args.kickass)


if __name__ == "__main__":
    main()
