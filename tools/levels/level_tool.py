#!/usr/bin/env python3
"""
Level table tool: compile a game's level definitions into KickAssembler data.

A level file is a Python file that defines:
  LEVELS     [dict, ...]  one per level, up to 255 (the game indexes them with one byte)
  TABLES     [(label, key), ...]  key holds one byte: emitted as `label:` with one byte per level
  RECORDS    [(label, key), ...]  key holds a list of bytes: emitted with `label_lo:`/`label_hi:`
             pointer tables, so levels can differ in length
optional:
  TITLE      name used in generated comments and the review page
  OUTPUT     output prefix (default: the file's stem)
  CONSTS     {NAME: value} extra .const lines
  CHECK      function(levels): raise or assert when the levels break a rule of the game
  COLUMNS    [key, ...] columns of the review page (default: every key holding a number)

Outputs next to the level file:
  <OUTPUT>_levels.asm    LEVEL_COUNT, the tables and records
  <OUTPUT>_review.html   one row per level, to read a difficulty curve at a glance

  python level_tool.py ../../game_dev/Heliscape/map/heliscape_levels.py
"""
import argparse
import html
import importlib.util
import pathlib
import sys


def load_def(path):
    sys.path.insert(0, str(path.parent))
    spec = importlib.util.spec_from_file_location(path.stem, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def as_byte(value, where):
    if not isinstance(value, int) or not 0 <= value <= 255:
        raise SystemExit(f"{where}: {value!r} does not fit a byte")
    return value


def byte_lines(values, per=16):
    return ["    .byte " + ",".join(f"${v:02X}" for v in values[i:i + per]) for i in range(0, len(values), per)]


def write_asm(d, title, levels, path):
    out = [f"// {title} levels - generated by tools/levels/level_tool.py, do not edit by hand",
           f".const LEVEL_COUNT = {len(levels)}"]
    for name, value in getattr(d, "CONSTS", {}).items():
        out.append(f".const {name} = {value}")
    size = 0
    for label, key in getattr(d, "TABLES", []):
        data = [as_byte(lv[key], f"level {i + 1} {key}") for i, lv in enumerate(levels)]
        out.append(f"{label}:")
        out += byte_lines(data)
        size += len(data)
    for label, key in getattr(d, "RECORDS", []):
        rows = [[as_byte(v, f"level {i + 1} {key}") for v in lv[key]] for i, lv in enumerate(levels)]
        for part, op in (("lo", "<"), ("hi", ">")):
            out.append(f"{label}_{part}:")
            refs = [f"{op}{label}_{i}" for i in range(len(rows))]
            out += ["    .byte " + ",".join(refs[i:i + 8]) for i in range(0, len(refs), 8)]
        size += 2 * len(rows)
        for i, row in enumerate(rows):
            out.append(f"{label}_{i}:")
            out += byte_lines(row)
            size += len(row)
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    return size


def write_review(d, title, levels, path):
    columns = getattr(d, "COLUMNS", None) or [k for k, v in levels[0].items() if isinstance(v, int)]
    head = "".join(f"<th>{html.escape(str(c))}</th>" for c in ["level", *columns])
    rows = "".join("<tr><td>" + str(i + 1) + "</td>" + "".join(f"<td>{html.escape(str(lv[c]))}</td>" for c in columns)
                   + "</tr>" for i, lv in enumerate(levels))
    path.write_text(
        f"<!doctype html><meta charset='utf-8'><title>{html.escape(title)} levels</title>"
        "<style>body{font:14px sans-serif;background:#111;color:#ddd;padding:16px}"
        "table{border-collapse:collapse}td,th{border:1px solid #444;padding:2px 8px;text-align:right}"
        "th{position:sticky;top:0;background:#222}</style>"
        f"<h1>{html.escape(title)}: {len(levels)} levels</h1><table><tr>{head}</tr>{rows}</table>\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("levels", type=pathlib.Path)
    args = ap.parse_args()
    src = args.levels.resolve()
    d = load_def(src)
    levels = d.LEVELS
    if not 1 <= len(levels) <= 255:
        raise SystemExit(f"{len(levels)} levels: the game indexes them with one byte (1-255)")
    check = getattr(d, "CHECK", None)
    if check:
        check(levels)
    title = getattr(d, "TITLE", src.stem)
    prefix = getattr(d, "OUTPUT", src.stem)
    asm = src.parent / f"{prefix}_levels.asm"
    size = write_asm(d, title, levels, asm)
    print(f"wrote {asm.name}: {len(levels)} levels, {size} bytes")
    page = src.parent / f"{prefix}_levels_review.html"
    write_review(d, title, levels, page)
    print(f"wrote {page.name}")


if __name__ == "__main__":
    main()
